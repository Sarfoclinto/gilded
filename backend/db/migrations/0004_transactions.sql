-- 0004 Customer transactions (purchases of gold) and cash drawer movements.
-- A transaction's cash payout and goods received live in the ledger (source_type transaction_*), not in
-- copies on this table: one place for every note and every gram.

create table gold.transactions (
  id                uuid primary key default gen_random_uuid(),                       -- generated by the device, doubles as Idempotency-Key
  tenant_id         uuid not null,
  branch_id         uuid not null,
  business_day_id   uuid,
  reference         text not null,
  customer_id       uuid,
  customer_name     text not null,
  customer_phone    text,
  status            text not null default 'saved' check (status in ('saved', 'paid', 'void')),
  formula_version   text not null,
  price_as_of       timestamptz not null,
  client_amount     numeric(18,2) not null,                 -- what the device calculated
  calculated_amount numeric(18,2) not null,                 -- what the server calculated and keeps
  payout_policy     text not null check (payout_policy in ('down', 'up', 'nearest')),
  payout_strategy   text not null check (payout_strategy in ('fewest-notes', 'prefer-100s')),
  payable           numeric(18,2) not null check (payable >= 0),
  payout_difference numeric(18,2) not null,
  captured_at       timestamptz not null,
  created_at        timestamptz not null default now(),
  created_by        uuid not null,
  flags             text[] not null default '{}',           -- OFFLINE_ENTRY, CALC_MISMATCH, PRICE_STALE, NO_OPEN_DAY
  voided_at         timestamptz,
  voided_by         uuid,
  void_reason       text,
  unique (tenant_id, id),
  unique (tenant_id, branch_id, reference),
  foreign key (tenant_id, branch_id)       references gold.branches (tenant_id, id),
  foreign key (tenant_id, business_day_id) references gold.business_days (tenant_id, id),
  foreign key (tenant_id, customer_id)     references gold.customers (tenant_id, id),
  foreign key (tenant_id, created_by)      references gold.users (tenant_id, id),
  foreign key (tenant_id, voided_by)       references gold.users (tenant_id, id),
  foreign key (tenant_id, formula_version) references gold.formula_versions (tenant_id, key),
  check (status <> 'void' or (voided_at is not null and voided_by is not null and gold.has_text(void_reason, 5)))
);
create index transactions_branch_time on gold.transactions (tenant_id, branch_id, captured_at desc);
create index transactions_customer    on gold.transactions (tenant_id, customer_id) where customer_id is not null;

-- Each piece of gold a customer brought. Items are the "lots" a transfer can later point at, so
-- "where did this customer's gold go" has an answer.
create table gold.transaction_items (
  id                 uuid primary key default gen_random_uuid(),
  tenant_id          uuid not null,
  transaction_id     uuid not null,
  line_no            smallint not null check (line_no > 0),
  label              text,
  top                numeric(14,4) not null check (top > 0),
  down               numeric(14,4) not null check (down > 0),
  price              numeric(18,2) not null check (price >= 0),
  density            numeric(10,2) not null,
  karat              numeric(10,2) not null,
  purity             numeric(10,4) not null,
  net_weight         numeric(14,4) not null,
  pounds             numeric(14,4) not null,
  amount             numeric(18,2) not null,
  -- Where this gold physically is right now. Moved by transfers; the full history is in transfer_goods_lines.
  location_branch_id uuid not null,
  location_state     text not null default 'on_hand' check (location_state in ('on_hand', 'in_transit')),
  unique (tenant_id, id),
  unique (transaction_id, line_no),
  foreign key (tenant_id, transaction_id)     references gold.transactions (tenant_id, id),
  foreign key (tenant_id, location_branch_id) references gold.branches (tenant_id, id)
);
create index transaction_items_location on gold.transaction_items (tenant_id, location_branch_id, location_state);

-- Cash put into or taken out of a drawer outside customer payouts (restock, end-of-day sweep, errands).
-- The notes themselves are ledger rows with source_type 'drawer_movement' and source_id = this id.
create table gold.drawer_movements (
  id               uuid primary key default gen_random_uuid(),
  tenant_id        uuid not null,
  branch_id        uuid not null,
  business_day_id  uuid,
  kind             text not null check (kind in ('topup', 'withdrawal')),
  note             text not null check (gold.has_text(note, 1)),
  occurred_at      timestamptz not null,
  created_by       uuid not null,
  created_at       timestamptz not null default now(),
  unique (tenant_id, id),
  foreign key (tenant_id, branch_id)       references gold.branches (tenant_id, id),
  foreign key (tenant_id, business_day_id) references gold.business_days (tenant_id, id),
  foreign key (tenant_id, created_by)      references gold.users (tenant_id, id)
);
create trigger drawer_movements_immutable before update or delete on gold.drawer_movements
  for each row execute function gold.forbid_mutation();
